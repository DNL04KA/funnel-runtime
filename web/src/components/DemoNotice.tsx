/**
 * Честное предупреждение для стенда на бесплатном хостинге.
 *
 * Показывается, только когда сервер запущен с DEMO_SEED_SESSIONS. Нужно,
 * чтобы сброс данных после рестарта инстанса не читался как баг продукта:
 * сама логика откатов аналитику не теряет, это ограничение эфемерного диска.
 */
export function DemoNotice({ show }: { show: boolean }): JSX.Element | null {
  if (!show) return null;
  return (
    <div className="notice notice--demo">
      <b>Демонстрационный стенд на бесплатном инстансе.</b> Диск эфемерный: при
      перезапуске база пересоздаётся, и сервер заново засевает версии и
      синтетический трафик. Опубликованные вами версии и пройденные сессии живут
      до следующего рестарта. На постоянном диске всё переживает перезапуск —
      конфигурация в <code>render.yaml</code>.
    </div>
  );
}
